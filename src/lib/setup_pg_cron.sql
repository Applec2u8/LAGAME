-- ===================================================
-- STEP 1: เปิดใช้งาน pg_cron extension
-- (ทำแค่ครั้งเดียว)
-- ===================================================
CREATE EXTENSION IF NOT EXISTS pg_cron;

-- ===================================================
-- STEP 2: ตั้งค่า Cron Job ให้รันทุก 1 นาที
-- (จะเรียก process_due_boost_schedules() อัตโนมัติ)
-- ===================================================
SELECT cron.schedule(
  'auto-boost-runner',      -- ชื่อ job (ต้องไม่ซ้ำ)
  '* * * * *',              -- ทุก 1 นาที (cron syntax)
  $$
    SELECT process_due_boost_schedules();
  $$
);

-- ===================================================
-- ดู Jobs ที่มีอยู่ทั้งหมด
-- ===================================================
SELECT * FROM cron.job;

